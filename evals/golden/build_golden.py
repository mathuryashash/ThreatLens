def main():
    seed = json.load(open(os.path.join(HERE, "seed_live_212.json"), encoding="utf-8"))
    rows = []
    for k in seed:
        rows.append(dict(stream=k["file"], idx=k["idx"], line=k["line"], label=k["label"], category=k["attack"],
                         subtle=bool(k["subtle"]), hard_negative=False, origin="live_qa_212"))
    # Seed lines that are hard negatives by construction (gen_logs.py FP traps / sample benign typo-login)
    traps = ("select+a+union+rep", "sql-injection-prevention-guide", "/api/export?format=csv&month=",
             "POST /api/login HTTP/1.1\" 401", "Failed password for alice from 192.168.1.20",
             "Accepted password for alice from 192.168.1.20", "Googlebot", "COMMAND=/usr/bin/systemctl restart nginx")
    for r_ in rows:
        if r_["label"] == "benign" and any(t in r_["line"] for t in traps):
            r_["hard_negative"] = True
    for stream, gen in [("nginx2", nginx2()), ("auth2", auth2()), ("inject_dev", inject("dev")), ("inject_test", inject("test"))]:
        for i, (line, lab, cat, subtle, hn) in enumerate(gen):
            rows.append(dict(stream=stream, idx=i, line=line, label=lab, category=cat, subtle=subtle,
                             hard_negative=hn, origin="evals_v1"))
    for r_ in rows:
        r_["source_type"] = SOURCE[r_["stream"]]
        r_["split"] = SPLIT[r_["stream"]]
        r_["id"] = f'{r_["stream"]}:{r_["idx"]}'
        assert r_["label"] in (B, A)
        assert (r_["label"] == A) == (r_["category"] is not None), r_
    ids = [r_["id"] for r_ in rows]
    assert len(ids) == len(set(ids))
    with open(os.path.join(HERE, "golden.jsonl"), "w", encoding="utf-8", newline="\n") as f:
        for r_ in rows:
            f.write(json.dumps(r_, ensure_ascii=False) + "\n")
    from collections import Counter
    print("total", len(rows), dict(Counter((r_["split"], r_["label"]) for r_ in rows)))
    print("hard negatives", sum(r_["hard_negative"] for r_ in rows))
    print("categories", dict(Counter((r_["split"], r_["category"]) for r_ in rows if r_["category"])))


if __name__ == "__main__":
    main()
